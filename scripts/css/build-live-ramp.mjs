/**
 * build-live-ramp.mjs — emits the opt-in runtime ramp.
 *
 * See `scripts/tokens/lib/live-ramp.mjs` for why this exists and why
 * `color-mix()` was not enough. In short: a Modyo site overrides CSS
 * variables with no build step, and overriding `--df-color-blue-500` today
 * leaves the other ten steps as tints of the old hue.
 *
 * Opt-in, and the default is unchanged. The committed hex literals stay
 * exactly as they are — Figma reads them, `tokens:validate` measures contrast
 * against them, and a page that does not link this file renders the same
 * colours it did before. This sheet only redefines the ten derived steps in
 * terms of the 500, so overriding one variable moves the ramp.
 *
 * The round-trip is checked: evaluating every expression against its own seed
 * reproduces the committed literal to the byte, across all eleven families. A
 * sheet that quietly shifted the palette would be worse than no sheet.
 */

import { buildRamp, STEPS } from '../tokens/lib/ramps.mjs';
import { stepCoefficients, stepValue, evaluate } from '../tokens/lib/live-ramp.mjs';
import { oklchToHex } from '../tokens/lib/color.mjs';
import { FAMILIES } from '../tokens/build-primitives.mjs';

export function buildLiveRamp() {
  const out = [
    '/*!',
    ' * Live ramp — GENERATED by scripts/css/build-live-ramp.mjs. Do not edit.',
    ' *',
    ' * OPT-IN. Link this AFTER dynamic.css to make every palette step derive',
    ' * from its own 500 at runtime:',
    ' *',
    ' *   <link rel="stylesheet" href=".../dynamic.css">',
    ' *   <link rel="stylesheet" href=".../dynamic.live-ramp.css">',
    ' *   <style>:root { --df-color-blue-500: #0a7d4b; }</style>',
    ' *',
    ' * Without it the steps are the committed literals and overriding a 500',
    ' * moves only that one step. With it, the ramp follows.',
    ' *',
    ' * Needs relative colour syntax: Chrome 119, Safari 16.4, Firefox 128.',
    ' * Every value here evaluates to the literal it replaces, so a browser',
    ' * without it simply keeps the literals.',
    ' */',
    '@layer df.tokens {',
    '  :root {',
  ];

  const mismatches = [];
  let count = 0;

  for (const [family, { seed }] of Object.entries(FAMILIES)) {
    const ramp = buildRamp(seed);
    out.push(`    /* ${family} — derived from --df-color-${family}-500 */`);

    for (const coefficient of stepCoefficients(seed, ramp)) {
      if (coefficient.seed) continue;

      const value = stepValue(family, coefficient);
      out.push(`    --df-color-${family}-${coefficient.step}: ${value};`);
      count += 1;

      const got = oklchToHex(evaluate(seed, coefficient));
      if (got.toLowerCase() !== ramp[coefficient.step].toLowerCase()) {
        mismatches.push(`${family}-${coefficient.step}: expression gives ${got}, literal is ${ramp[coefficient.step]}`);
      }
    }
    out.push('');
  }

  out.push('  }');
  out.push('}');
  out.push('');

  return { css: out.join('\n'), count, mismatches, steps: STEPS.length };
}

if (process.argv[1] && process.argv[1].endsWith('build-live-ramp.mjs')) {
  const { css } = buildLiveRamp();
  process.stdout.write(css);
}
