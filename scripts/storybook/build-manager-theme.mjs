/**
 * build-manager-theme.mjs — the Storybook chrome, from the design tokens.
 *
 * The manager — the sidebar, the toolbar, the docs chrome — is a separate
 * React app from the preview, so it cannot read a CSS custom property set on
 * the story's document. `storybook/theming` wants concrete values at config
 * time, which is how `.storybook/theme.ts` ended up carrying hand-written
 * hexes: `#fbfaff`, `#2068d5`, `#e6e6f3`. Six colours of the design system,
 * copied, with nothing holding them to it.
 *
 * So they are generated. The same `tokens/` files the stylesheet is built from
 * produce both themes, and `npm run css:generated` notices if the output stops
 * matching its source — the same discipline the rest of the token pipeline is
 * under.
 *
 * Usage: node scripts/storybook/build-manager-theme.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = (file) => JSON.parse(readFileSync(resolve(ROOT, file), 'utf8'));

/** `{ "neutral.900": "#…" }` from a DTCG tree. */
function flatten(tree, prefix = '') {
  const out = {};
  Object.entries(tree).forEach(([key, value]) => {
    if (key.startsWith('$')) return;
    if (value && typeof value === 'object' && '$value' in value) out[prefix + key] = value.$value;
    else if (value && typeof value === 'object') Object.assign(out, flatten(value, `${prefix}${key}.`));
  });
  return out;
}

const primitives = flatten(read('tokens/primitives/color.json').color);

/**
 * Follows a `{color.neutral.900}` reference down to a literal.
 *
 * Bounded rather than trusting the data: a cycle in the tokens would otherwise
 * hang the build with no message, and the token validator already fails on
 * one — this is the second line of defence, not the first.
 */
function resolveRef(value, depth = 0) {
  if (typeof value !== 'string' || depth > 8) return value;
  const match = /^\{([^}]+)\}$/.exec(value.trim());
  if (!match) return value;
  const key = match[1].replace(/^color\./, '');
  if (!(key in primitives)) {
    throw new Error(`manager-theme: {${match[1]}} does not resolve to a primitive`);
  }
  return resolveRef(primitives[key], depth + 1);
}

function paletteFor(mode) {
  /* `role` lives in the same per-mode file: the accent has to differ between
     light and dark too, so it is not a shared value. */
  const semantic = flatten(read(`tokens/semantic/color.${mode}.json`));

  const pick = (name) => {
    if (!(name in semantic)) throw new Error(`manager-theme: ${name} is missing in ${mode}`);
    return resolveRef(semantic[name]);
  };

  return {
    appBg: pick('bg.canvas'),
    appContentBg: pick('bg.surface'),
    appPreviewBg: pick('bg.canvas'),
    appBorderColor: pick('border.default'),
    textColor: pick('fg.default'),
    textMutedColor: pick('fg.muted'),
    textInverseColor: pick('fg.inverse'),
    barBg: pick('bg.surface'),
    barTextColor: pick('fg.muted'),
    /* The accent is a role, not a surface — and it is per-mode, because a blue
       that reads on white is not the blue that reads on near-black. */
    colorPrimary: pick('role.primary.base'),
    colorSecondary: pick('role.primary.base'),
    inputBg: pick('bg.surface'),
    inputBorder: pick('border.default'),
    inputTextColor: pick('fg.default'),
  };
}

const serialise = (palette) => Object.entries(palette)
  .map(([key, value]) => `    ${key}: '${value}',`)
  .join('\n');

const file = `/*
 * GENERATED by scripts/storybook/build-manager-theme.mjs. Do not edit.
 *
 * The chrome's colours, from the same \`tokens/\` the stylesheet is built from.
 * Hand-written hexes here drifted from the design system silently, because
 * nothing compares a Storybook theme to anything.
 */

export const palette = {
  light: {
${serialise(paletteFor('light'))}
  },
  dark: {
${serialise(paletteFor('dark'))}
  },
} as const;

export type ThemeName = keyof typeof palette;
`;

writeFileSync(resolve(ROOT, '.storybook/palette.ts'), file);
process.stdout.write('storybook: .storybook/palette.ts written from tokens/\n');
